export type Agent = {
  id: string;
  name: string;
  skills: number;
};

export type Skill = {
  name: string;
  version: string;
  category: string;
  /** Short, language-neutral labels the leaderboard filters and the detail page badges with. */
  tags: string[];
  description: string;
  repo: string;
  homepage: string;
  compat: string[];
  stats: {
    totalCommits: number;
    commits8w: number;
    commits7d: number;
    /** Commit counts for the 8 rolling weekly buckets, oldest first. */
    weekly: number[];
    firstCommit: string | null;
    lastCommit: string | null;
    contributors: number;
  };
};

export type SortKey = "all" | "trending" | "hot" | "commits" | "updated";

/** Languages a published README exists in; must stay in lockstep with the
 *  READMES map in scripts/sync-skills.mjs. */
export type DocLang = "en" | "zh";

/** The source file each language's published README is generated from. */
export const DOC_SOURCES: Record<DocLang, string> = {
  en: "README.md",
  zh: "README.zh-CN.md",
};

/** Public data path of a skill's published README, e.g. data/skills/web-markdown/README.en.md. */
export function readmePath(skillName: string, lang: DocLang): string {
  return `data/skills/${skillName}/README.${lang}.md`;
}

/** GitHub location of the source README a published doc was generated from. */
export function readmeSourceUrl(skillName: string, lang: DocLang): string {
  return `${repoMeta.repoUrl}/blob/main/skills/${skillName}/${DOC_SOURCES[lang]}`;
}

/** The shape of public/data/skills.json, regenerated by `npm run sync:skills`. */
export type SkillsData = {
  /** UTC+8 timestamp of the sync that produced the file. */
  generatedAt: string;
  repo: string;
  repoUrl: string;
  installPrefix: string;
  agents: Agent[];
  skills: Skill[];
};

/**
 * Site identity. This is configuration, not generated data: it is what the
 * build bakes into titles, OG cards and install commands, and it is the only
 * thing that has to change when the directory is forked for another repo.
 * The generated dataset carries the same values so a mismatch is visible in CI.
 */
export const repoMeta = {
  repo: "chaos-design/skills",
  repoUrl: "https://github.com/chaos-design/skills",
  installPrefix: "npx skills add https://github.com/chaos-design/skills --skill",
} as const;

/** Install command for one skill, built from the site's own configuration. */
export function installCommand(skillName: string): string {
  return `${repoMeta.installPrefix} ${skillName}`;
}

/**
 * The Prompt tab's text: what to hand an agent that has the skills CLI. It
 * mirrors the upstream `npx skills use` flow — install, read the whole
 * generated output, and resolve the skill's relative paths from the
 * supporting-files directory — so the agent does not stop half way.
 *
 * Deliberately English in both locales: an agent reads it, not a visitor.
 */
export function agentPrompt(skillName: string): string {
  return `Run \`npx skills use "${repoMeta.repoUrl}" --skill "${skillName}"\` and follow the generated skill instructions now. Read its complete output, redirecting it to a temporary file first if necessary. Resolve relative paths from the supporting-files directory it provides.`;
}

/** Case-insensitive match across the fields a visitor would search by. */
export function filterSkills(list: Skill[], query: string): Skill[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return list;
  return list.filter((skill) =>
    [skill.name, skill.repo, skill.category, ...skill.tags, skill.description].some((field) =>
      field.toLowerCase().includes(needle),
    ),
  );
}

/**
 * Narrow a list by the selected tag chips. A skill matches only when it carries
 * every selected tag (AND) — picking "slides" then "presentation" leaves the
 * slide decks. No selection returns the list unchanged.
 */
export function filterByTags(list: Skill[], selected: readonly string[]): Skill[] {
  if (selected.length === 0) return list;
  return list.filter((skill) => selected.every((tag) => skill.tags.includes(tag)));
}

/**
 * Every distinct tag across the dataset with its member count, most common
 * first (ties alphabetical). Feeds the leaderboard's filter chips; a count of
 * one still shows, so single-skill labels stay filterable.
 */
export function tagCounts(list: Skill[]): { tag: string; count: number }[] {
  const counts = new Map<string, number>();
  for (const skill of list) {
    for (const tag of skill.tags) {
      counts.set(tag, (counts.get(tag) ?? 0) + 1);
    }
  }
  return [...counts.entries()]
    .map(([tag, count]) => ({ tag, count }))
    .sort((a, b) => b.count - a.count || a.tag.localeCompare(b.tag));
}

/** Sort by the metric each leaderboard tab stands for. */
export function sortSkills(list: Skill[], key: SortKey): Skill[] {
  const rows = [...list];
  switch (key) {
    case "trending":
      return rows.sort(
        (a, b) =>
          b.stats.commits7d - a.stats.commits7d ||
          dateValue(b.stats.lastCommit) - dateValue(a.stats.lastCommit) ||
          a.name.localeCompare(b.name),
      );
    case "hot":
      return rows.sort(
        (a, b) =>
          dateValue(b.stats.lastCommit) - dateValue(a.stats.lastCommit) ||
          b.stats.totalCommits - a.stats.totalCommits ||
          a.name.localeCompare(b.name),
      );
    case "commits":
      return rows.sort(
        (a, b) =>
          b.stats.totalCommits - a.stats.totalCommits ||
          dateValue(b.stats.lastCommit) - dateValue(a.stats.lastCommit) ||
          a.name.localeCompare(b.name),
      );
    case "updated":
      return rows.sort(
        (a, b) =>
          dateValue(b.stats.lastCommit) - dateValue(a.stats.lastCommit) ||
          b.stats.totalCommits - a.stats.totalCommits ||
          a.name.localeCompare(b.name),
      );
    default:
      return rows.sort(
        (a, b) =>
          b.stats.totalCommits - a.stats.totalCommits ||
          dateValue(b.stats.lastCommit) - dateValue(a.stats.lastCommit) ||
          a.name.localeCompare(b.name),
      );
  }
}

/** Look up a single skill by its name; undefined when the page is unknown. */
export function getSkillByName(list: Skill[], name: string): Skill | undefined {
  return list.find((skill) => skill.name === name);
}

/**
 * Nearest neighbours for the detail page: skills in the same category group
 * first (most active first), padded with the most active skills overall when a
 * category has fewer than `limit` members. The source skill is never included.
 */
export function relatedSkills(list: Skill[], skill: Skill, limit = 4): Skill[] {
  const sameCategory = list.filter(
    (candidate) => candidate.name !== skill.name && candidate.category === skill.category,
  );
  const others = list.filter(
    (candidate) => candidate.name !== skill.name && candidate.category !== skill.category,
  );
  const byActivity = (a: Skill, b: Skill) =>
    b.stats.commits8w - a.stats.commits8w ||
    b.stats.totalCommits - a.stats.totalCommits ||
    a.name.localeCompare(b.name);
  return [...sameCategory.sort(byActivity), ...others.sort(byActivity)].slice(0, limit);
}

function dateValue(iso: string | null): number {
  return iso ? Date.parse(`${iso}T00:00:00Z`) : 0;
}

/** 1286544 -> "1.3M"; small numbers stay exact. */
export function formatCompact(value: number): string {
  if (value < 1000) return String(value);
  if (value < 1_000_000) return `${trimZero(value / 1000)}K`;
  return `${trimZero(value / 1_000_000)}M`;
}

function trimZero(value: number): string {
  const fixed = value >= 100 ? value.toFixed(0) : value.toFixed(1);
  return fixed.replace(/\.0$/, "");
}

/** "2026-10-09" -> "Oct 9, 2026" (UTC, so output never depends on the host TZ). */
export function formatDate(iso: string | null): string {
  if (!iso) return "—";
  return new Date(`${iso}T00:00:00Z`).toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC",
  });
}
